class WeatherService {
  String getWeatherDescription(double temp, double humidity) {
    return switch ((temp, humidity)) {
      ( > 30, > 70) => "Жарко и влажно, возможна гроза",
      ( > 30, _)    => "Жарко и сухо",
      ( > 15, > 60) => "Приятная теплая погода, но влажно",
      ( > 15, _)    => "Отличная погода для прогулки",
      ( > 0, _)     => "Прохладно, оденьтесь теплее",
      _             => "Морозно, оставайтесь дома",
    };
  }
}
